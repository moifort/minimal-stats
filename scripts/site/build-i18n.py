#!/usr/bin/env python3
"""Writes site/i18n/<code>.js, the landing page's 24 languages besides French,
from scripts/site/translations_*.py. French is site/index.html itself.

    python3 scripts/site/build-i18n.py

Fails when a language misses a text the page has (data-i18n, data-i18n-aria)
or keeps a placeholder. Run it after changing a text, as Dictate's
DEVELOPMENT.md asks: a new text goes into index.html in French and into each
language here."""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SITE = ROOT / "site"

T = {}
for part in sorted((ROOT / "scripts/site").glob("translations_*.py")):
    scope = {}
    exec(part.read_text(encoding="utf-8"), scope)
    T.update(scope["T"])

# Activity Monitor as each language's macOS calls it; English where macOS is
# not localized (Estonian, Latvian, Lithuanian, Maltese, Slovenian), as
# Dictate's site does for system settings.
ACTIVITY_MONITOR = {
    "en": "Activity Monitor", "de": "Aktivitätsanzeige", "es": "Monitor de Actividad",
    "it": "Monitoraggio Attività", "nl": "Activiteitenweergave", "pt": "Monitor de Atividade",
    "sv": "Aktivitetskontroll", "da": "Aktivitetsovervågning", "fi": "Toimintojen valvonta",
    "pl": "Monitorze aktywności", "cs": "Monitoru aktivity", "sk": "Monitore aktivity",
    "hu": "Tevékenységfigyelő", "ro": "Monitor activitate", "hr": "Monitoru aktivnosti",
    "sl": "Activity Monitor", "ru": "Мониторинг системы", "uk": "Моніторинг системи",
    "bg": "Activity Monitor", "el": "Παρακολούθηση δραστηριότητας", "et": "Activity Monitor",
    "lv": "Activity Monitor", "lt": "Activity Monitor", "mt": "Activity Monitor",
}
# The nominative where the sentence needs it (FAQ answer 4).
ACTIVITY_MONITOR_SUBJECT = {"pl": "Monitor aktywności", "cs": "Monitor aktivity", "sk": "Monitor aktivity", "hr": "Monitor aktivnosti"}
# Apple's own App Store badges, which exist in these languages only.
BADGES = {p.stem for p in (SITE / "badges").glob("*.svg")}

page = (SITE / "index.html").read_text(encoding="utf-8")
keys = list(dict.fromkeys(re.findall(r'data-i18n(?:-aria)?="([^"]+)"', page)))
keys += ["meta.description", "version"]

problems = []
for lang, text in sorted(T.items()):
    out = {}
    links = {
        "{DMG}": "<code>Stats.dmg</code>",
        "{PRIVACY}": f'<a href="privacy.html">{text["footer.privacy"]}</a>',
        "{POLYFORMS}": '<a href="https://github.com/moifort" rel="noopener">Polyforms</a>',
    }
    composed = dict(text)
    composed["hero.meta"] = f'{text["free"]} · Open source · <span data-version>{text["latest"]}</span> · macOS 26 · Apple Silicon'
    composed["dl.meta"] = f'<span data-version>{text["latest"]}</span> · macOS 26 · Apple Silicon'
    for key in keys:
        if key not in composed:
            problems.append(f"{lang}: no {key}")
            continue
        value = composed[key]
        name = ACTIVITY_MONITOR_SUBJECT.get(lang, ACTIVITY_MONITOR[lang]) if key == "faq.a4" else ACTIVITY_MONITOR[lang]
        value = value.replace("{AM}", name)
        for placeholder, html in links.items():
            value = value.replace(placeholder, html)
        if re.search(r"\{(?!v\})[A-Z]+\}", value):
            problems.append(f"{lang}: {key} keeps a placeholder")
        out[key] = value
    badge = f"badges/{lang}.svg" if lang in BADGES else "badges/en.svg"
    body = json.dumps({"text": out, "badge": badge}, ensure_ascii=False, indent=2)
    (SITE / "i18n" / f"{lang}.js").write_text(
        f'/* Stats landing page: its texts in "{lang}", read by i18n.js and main.js.\n'
        f"   Generated by scripts/site/build-i18n.py: edit the translations there. */\n"
        f"window.STATS_I18N = {body};\n",
        encoding="utf-8",
    )

if problems:
    print(*problems, sep="\n")
    sys.exit(1)
print(f"{len(T)} languages, {len(keys)} texts each")
